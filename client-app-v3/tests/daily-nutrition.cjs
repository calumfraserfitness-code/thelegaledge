const assert=require('node:assert/strict');
const M=require('../daily-nutrition-model.js');
const meals=[{name:'Breakfast',meal_type:'Breakfast',calories:400,protein_g:30,carbs_g:40,fat_g:10},{name:'Lunch',meal_type:'Main meal',calories:600,protein_g:40,carbs_g:70,fat_g:20},{name:'Dinner',meal_type:'Main meal',calories:550,protein_g:35,carbs_g:60,fat_g:18}];
let rows=M.slots(meals);
assert.deepEqual(rows.map(r=>r.group),['Breakfast','Lunch','Dinner']);
assert.deepEqual(M.slots([meals[0],{name:'Snack',meal_type:'Snack'},meals[1],meals[2]]).map(r=>r.group),['Breakfast','Snacks','Lunch','Dinner']);
assert.equal(M.totals(rows,true).calories,0,'Choosing meals is not eating them');
const entry={slot_key:'lunch-1',meal_snapshot:{...meals[1],name:'Lunch leftovers',calories:500},servings:1.5,eaten:true};
rows=M.slots(meals,[entry]);
assert.equal(rows[1].meal.name,'Lunch leftovers');
assert.equal(M.totals(rows,true).calories,750);
assert.equal(M.totals(rows).calories,1700);
assert.equal(meals[1].calories,600,'Swaps leave the assigned plan intact');
rows=M.slots(meals,[entry,{slot_key:'quick-1',meal_snapshot:{name:'Unknown snack',calories:null,protein_g:10},eaten:true,servings:1}]);
assert.equal(M.totals(rows,true).calories,null,'Missing calories never count as zero');
assert.equal(M.totals(rows,true).protein_g,70);
assert.equal(M.totals(rows,true).carbs_g,null);
assert.equal(M.slots([], [entry]).length,1,'History survives removed assignments');
assert.equal(M.number(''),null);assert.equal(M.number(null),null);assert.equal(M.number(-1),null);assert.equal(M.number('n/a'),null);assert.equal(M.number(0),0);
assert.equal(M.targets({calorie_goal:2100},{calories:2000},{calorie_target:1900}).calories,1900);
assert.equal(M.targets({protein_goal_g:150},{protein_g:null},null).protein_g,150);
assert.equal(M.targets({},null,null).fat_g,null);
assert.equal(M.comparable(meals[1],{calories:630,protein_g:42}),true);
assert.equal(M.comparable(meals[1],{calories:1100,protein_g:42}),false);
assert.equal(M.comparable(meals[1],{calories:null,protein_g:42}),false);
assert.equal(M.snapshot({name:'Real meal',calories:null}).calories,null);
console.log('PASS: assigned menus preserved, dated slot replacement, chosen vs eaten totals, portion scaling, unknown values, deleted-menu history and target precedence.');
