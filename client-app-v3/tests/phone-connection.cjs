const fs=require('fs'),vm=require('vm'),assert=require('assert');
const context=vm.createContext({navigator:{userAgent:'desktop',maxTouchPoints:0},location:{origin:'https://legal-edge-client-app.vercel.app',pathname:'/',search:'?setup=health&token=private&client_id=another'},URL});
vm.runInContext(fs.readFileSync(__dirname+'/../phone-connection.js','utf8'),context);
assert.equal(context.phonePlatform('Mozilla iPhone',0),'ios');
assert.equal(context.phonePlatform('Mozilla Macintosh',5),'ios');
assert.equal(context.phonePlatform('Mozilla Macintosh',0),'desktop');
assert.equal(context.phonePlatform('Mozilla Android',5),'android');
const safe=new URL(context.phoneSetupUrl());
assert.equal(safe.search,'?setup=health');
assert.equal(safe.searchParams.has('token'),false);
assert.equal(safe.searchParams.has('client_id'),false);
assert.equal(new URL(context.phoneSetupUrl(true)).searchParams.get('workspace'),'demo');
assert.equal(context.phoneMetricValue('steps',0),'0');
assert.equal(context.phoneMetricValue('steps',null),'Not received');
assert.equal(context.phoneMetricValue('steps',undefined),'Not received');
assert.equal(context.phoneMetricValue('weight_kg',NaN),'Not received');
assert.equal(context.phoneMetricValue('sleep_minutes',450),'7.5 h');
assert.equal(context.phoneMetricValue('protein_g',0),'0 g');
console.log('PASS: phone detection, safe handoff without credentials or client IDs, real zero values and missing readings.');
